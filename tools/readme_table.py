#! /usr/bin/env python3
"""Regenerate the table of Submodel templates at the end of the top-level README.md.

    python tools/readme_table.py            # rewrite README.md
    python tools/readme_table.py --check    # exit 1 if README.md is out of date

One row per version (major.minor) of every SMT under published/ and deprecated/.
The row links the newest release of that version, i.e. its newest bug-fix folder
(x/y/z) if there is one, else x/y. The name is the first heading of the README in
the x/y folder, without its "(Version ...)" suffix. The IDTA number comes from the
SMT's label in tools/smt-config.yml. Rows are ordered by IDTA number, then by version.
"""

import argparse
import pathlib
import re
import sys
import urllib.parse

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import repo  # noqa: E402

README = repo.ROOT / "README.md"
HEADER = "# Table of IDTA Submodel templates"
TREE = "https://github.com/admin-shell-io/submodel-templates/tree/main/"
BADGE = "![Template](https://img.shields.io/static/v1?style=plastic&label=SMT&message=Template&color=green)"
ARTIFACTS = (".json", ".aasx", ".pdf")


def has_artifacts(folder: pathlib.Path) -> bool:
    return any(f.is_file() and f.suffix.lower() in ARTIFACTS for f in folder.iterdir())


def smt_name(vfolder: pathlib.Path) -> str:
    readme = vfolder / "README.md"
    if readme.exists():
        for line in readme.read_text(encoding="utf-8", errors="replace").splitlines():
            if line.startswith("#"):
                name = re.sub(r"\s*\(\s*Version[^)]*\)\s*$", "", line.lstrip("#").strip())
                return re.sub(r"\s+", " ", name)
    return vfolder.parent.parent.name


def idta_order() -> dict:
    """SMT folder -> sort key from its IDTA number label."""
    out = {}
    for label, folder in repo.load_config()["smts"].items():
        m = re.search(r"(\d{5})(?:-(\d+))?", label)
        if m:
            out[folder] = (int(m.group(1)), int(m.group(2) or 0), label)
    return out


def rows() -> list:
    order = idta_order()
    found = []
    for kind, root in (("Published", repo.ROOT / "published"), ("Deprecated", repo.ROOT / "deprecated")):
        for vfolder in sorted(p for p in root.rglob("*") if p.is_dir()):
            parts = vfolder.relative_to(root).parts
            if len(parts) < 3 or not (parts[-1].isdigit() and parts[-2].isdigit()) or parts[-3].isdigit():
                continue
            if not has_artifacts(vfolder):
                continue
            patches = [p for p in vfolder.iterdir() if p.is_dir() and p.name.isdigit() and has_artifacts(p)]
            newest = max(patches, key=lambda p: int(p.name)) if patches else vfolder
            smt = "/".join(parts[:-2])
            major, minor = int(parts[-2]), int(parts[-1])
            fix = int(newest.name) if patches else 0
            version = f"{major}.{minor}" + (f".{fix}" if fix else "")
            link = TREE + urllib.parse.quote(newest.relative_to(repo.ROOT).as_posix())
            key = (kind != "Published", order.get(smt, (99999, 0, smt)), major, minor)
            label = order.get(smt, (0, 0, ""))[2]
            number = re.match(r"IDTA \d{5}(?:-\d+)?", label)
            found.append((key, f"| {kind} | {number.group(0) if number else ''} | [{smt_name(vfolder)} (Version {version})]({link}) | "
                               f"{major} | {minor} | {fix} | {BADGE} |"))
    return [line for _, line in sorted(found)]


def table() -> str:
    return "\n".join([
        HEADER,
        "",
        "(generated by `python tools/readme_table.py` from the folders under published/ and deprecated/; "
        "each row links the newest release of a version, including its bug fixes)",
        "",
        "| Type SMT | IDTA No. | Name | Ver | Rev | Bug Fix | Criteria |",
        "|  ---------- |  ---------- |  ---------- |  ---------- |  ---------- |  ---------- |  ---------- |",
        *rows(),
        "",
    ])


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only report whether README.md is up to date")
    args = ap.parse_args()
    text = README.read_text(encoding="utf-8")
    head, sep, _ = text.partition(HEADER)
    if not sep:
        print(f"::error::{README.name} has no '{HEADER}' section")
        return 2
    newline = "\r\n" if "\r\n" in head else "\n"
    new = head + table().replace("\n", newline)
    if args.check:
        if new != text:
            print("README.md table is out of date; run python tools/readme_table.py")
            return 1
        print("README.md table is up to date")
        return 0
    README.write_bytes(new.encode("utf-8"))
    print(f"README.md: {len(rows())} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
